<p>QuickBooks is a sensible place to start keeping books. As a business grows, though, owners often want things it does not do well for them: one system for stock, sales and accounts, access for many staff with limits on what each can see, several companies side by side, or reports shaped around how they actually run the business.</p>
<p>The worry that stops most moves is history. Years of vouchers sit in QuickBooks, and nobody wants to re-enter them. The good news is that you do not have to.</p>

<h2>1. Decide what "history" means for you</h2>
<p>There are two common approaches:</p>
<ul>
  <li><strong>Full history.</strong> Every posted transaction from the first day comes across, so ledgers and comparisons go back as far as QuickBooks does.</li>
  <li><strong>Opening balances.</strong> Only the trial balance on the switch date comes across, and QuickBooks stays available as a read-only archive.</li>
</ul>
<p>Full history is worth it when you compare years, answer auditors from the new system, or track customer and supplier balances over time.</p>

<h2>2. Export the Journal report</h2>
<p>The Journal report lists every transaction with its date, type, number, name, memo, account, debit and credit. That is everything an ERP needs to rebuild the ledgers.</p>
<ol>
  <li>In QuickBooks open <strong>Reports › Accountant &amp; Taxes › Journal</strong>.</li>
  <li>Set <strong>Dates</strong> to <em>All</em>, or from the first transaction to today.</li>
  <li>Export to Excel and save the file as <strong>.xlsx</strong>.</li>
  <li>If you run more than one company file, repeat this for each company.</li>
</ol>
<p>Also run the <strong>Trial Balance</strong> for the same date. You will use it to check the import.</p>

<h2>3. Match the chart of accounts</h2>
<p>Your QuickBooks accounts rarely line up one to one with a properly structured chart of accounts, especially one built for financial statements. During import, each QuickBooks account is matched once to an account in the new chart. Good tools remember these matches, so the second company or a later re-import only asks about new accounts.</p>
<div class="callout"><strong>Tip:</strong> clean up duplicate or unused QuickBooks accounts before exporting. It makes the matching step much quicker.</div>

<h2>4. Check before anything is saved</h2>
<p>A careful import shows you a check page first:</p>
<ul>
  <li>number of transactions and lines, and the first and last date,</li>
  <li>total debit and total credit, which must be equal, and</li>
  <li>any transaction that does not balance, so you can fix it in QuickBooks and export again.</li>
</ul>

<h2>5. Compare the trial balance</h2>
<p>After import, run the trial balance in the new system for the same date as the QuickBooks one. Totals should match exactly, and so should each matched account. Only when they do should anyone post new transactions.</p>

<h2>6. Pick a cut-over day and stick to it</h2>
<p>From the cut-over day, post only in the new system. Two live sets of books always drift apart. Keep QuickBooks for looking things up, not for entering them.</p>

<h2>What the Journal report does not bring</h2>
<p>The Journal carries the accounting entries. It does not carry customer and supplier master details, open invoices with due dates, fixed asset registers or payroll setup. If you need those in the new system from day one, plan a separate import for each.</p>

