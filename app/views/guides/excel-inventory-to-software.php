<p>Most small businesses start tracking stock in Excel. One sheet for items, one for purchases, one for sales, and a formula that works out what is left. It works well until more than one person needs to update it, or until the numbers on the sheet stop matching the shelf.</p>
<p>This guide walks through how to move that register into inventory software in a way that keeps your history, does not stop sales for a day, and leaves your team happier than before.</p>

<h2>1. Write down how stock really moves today</h2>
<p>Before touching any software, list every way stock enters or leaves the business. A typical list looks like this:</p>
<ul>
  <li>Purchases from suppliers (with or without a purchase order)</li>
  <li>Sales at the counter, by phone, or online</li>
  <li>Returns from customers and returns to suppliers</li>
  <li>Transfers between a shop and a warehouse</li>
  <li>Damaged, expired or missing items written off</li>
</ul>
<p>Then mark who records each one today, and where. This is the map the new system has to cover. Missing a single movement type, such as write-offs, is the most common reason stock figures drift again after a switch.</p>

<h2>2. Clean the item list first</h2>
<p>Your item list is the foundation. Spend an hour on it before importing anything:</p>
<ul>
  <li><strong>Remove duplicates.</strong> "Cement 50kg", "Cement bag 50 kg" and "cement" are usually the same item.</li>
  <li><strong>Give every item a code.</strong> A short SKU such as CEM-50 makes searching and barcode labels possible later.</li>
  <li><strong>Fix the unit.</strong> Decide whether you count in pieces, boxes or kilograms, and write it down per item.</li>
  <li><strong>Add a reorder level.</strong> The quantity at which you want to be warned. This is what turns software into something that saves money.</li>
</ul>

<h2>3. Decide what history you need</h2>
<p>You rarely need every row since the day the business opened. A practical rule is to bring over:</p>
<ul>
  <li>Opening stock for every item, counted on the day you switch</li>
  <li>The last 12 months of purchases and sales, for reports and seasonality</li>
  <li>Open supplier orders and customer orders that are not yet delivered</li>
</ul>
<p>Older data can stay in the original workbook as a read-only archive.</p>

<h2>4. Do a physical count on switch day</h2>
<p>Spreadsheet stock and real stock are almost never the same. Pick a quiet day, count the shelves, and use that count as the opening balance in the new system. Everything after that moment is recorded in the software only.</p>

<div class="callout"><strong>Tip:</strong> run the old sheet and the new system side by side for one week at most. Longer than that, and people keep updating the sheet out of habit.</div>

<h2>5. Give each person their own login</h2>
<p>The biggest gain from leaving Excel is not the screens. It is knowing who did what. Give every staff member their own login, and limit what each role can see. A counter salesperson does not need purchase prices, and a store keeper does not need the profit report.</p>

<h2>6. Set up the three reports you will actually read</h2>
<p>Inventory software can produce dozens of reports. Start with three:</p>
<ol>
  <li><strong>Low stock:</strong> items below their reorder level, to send to suppliers.</li>
  <li><strong>Stock value:</strong> what your shelves are worth today, for the owner and the accountant.</li>
  <li><strong>Slow movers:</strong> items that have not sold in 90 days, which are tying up cash.</li>
</ol>

<h2>7. Connect stock to sales and accounts</h2>
<p>Once stock is stable, the next step is to make every sale reduce stock and post to the books at the same time. That is what an ERP does, and it removes the double typing between the sales sheet, the stock sheet and the accounts sheet.</p>

