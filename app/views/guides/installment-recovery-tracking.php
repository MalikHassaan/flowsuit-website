<p>Housing projects, plot sellers and apartment developers usually sell on installments. That means hundreds or thousands of customers, each with a schedule of dues, partial payments, late payments and transfers. Most teams track it in Excel, and most of them know exactly when the sheet stopped being reliable.</p>
<p>This guide explains what a recovery system needs to do, and how to move from the spreadsheet without losing a single receipt.</p>

<h2>1. Why installment sheets break</h2>
<ul>
  <li><strong>One row per customer is not enough.</strong> Each customer has many dues and many receipts, and they rarely line up one to one.</li>
  <li><strong>Several people edit the same file.</strong> Recovery staff, accounts and management each keep their own copy.</li>
  <li><strong>Aging is calculated by hand.</strong> "How much is 90 days overdue?" takes an afternoon instead of a click.</li>
  <li><strong>Bank collections arrive in a separate file</strong> and have to be matched to customers manually.</li>
</ul>

<h2>2. What a recovery system should show</h2>
<p>Whatever tool you use, management usually asks for the same five views:</p>
<ol>
  <li><strong>Receipts against dues</strong> for each customer and for the whole project.</li>
  <li><strong>Overdue aging</strong> in buckets such as 0 to 30, 31 to 90 and over 90 days.</li>
  <li><strong>Number of installments paid</strong> and the percentage of the total price received.</li>
  <li><strong>Bank collection</strong> by day and by bank, matched to customers.</li>
  <li><strong>A recovery desk</strong>: who to call today, what they promised last time, and who followed up.</li>
</ol>

<h2>3. Keep the data where it is created</h2>
<p>Most developers already have the key data in their existing system or exports: the payment plan, the receipts and the bank statement. Instead of retyping it, a good recovery dashboard reads those exports directly, so the numbers come from the same source the accounts team uses.</p>

<h2>4. Give each person the right view</h2>
<ul>
  <li>Recovery officers see their own customers and log follow-ups.</li>
  <li>Accounts upload the latest exports and check totals.</li>
  <li>Management sees the project-wide picture and trends, without being able to change entries.</li>
</ul>

<h2>5. Move from Excel in a week, not a quarter</h2>
<ol>
  <li>Export the payment plans and receipts from your current system to Excel.</li>
  <li>Load them into the recovery system and compare totals with your sheet.</li>
  <li>Run both for a few days, then retire the sheet.</li>
</ol>

